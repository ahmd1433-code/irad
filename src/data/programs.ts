export function getProgram(slug: string) {
  return programs.find((program) => program.slug === slug);
}

export function getFeaturedPrograms() {
  return programs.filter((program) => program.featured);
}

export function getRelatedPrograms(slug: string, limit = 3) {
  const current = getProgram(slug);
  if (!current) return programs.slice(0, limit);
  return programs
    .filter((program) => program.slug !== slug)
    .sort((a, b) => {
      const aScore = a.models.some((model) => current.models.includes(model))
        ? 1
        : 0;
      const bScore = b.models.some((model) => current.models.includes(model))
        ? 1
        : 0;
      return bScore - aScore;
    })
    .slice(0, limit);
}
